-- F5：客户授信与回款核销（客户信用额度 / 额度版本审批 / 上刊占用与撤刊释放 / 回款按单分次核销）

-- 客户编号、回款凭证号全局序列
CREATE SEQUENCE IF NOT EXISTS seq_customer_no START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_payment_no START WITH 1 INCREMENT BY 1;

-- 上刊单补授信关联：引用报价单的单据占用授信，客户与含税占用额从报价单快照固化；
-- 不引用报价单的单据保持 F1 原样，credit_used = 0，不占额度
ALTER TABLE t_posting_order ADD COLUMN IF NOT EXISTS quote_no VARCHAR(40);
ALTER TABLE t_posting_order ADD COLUMN IF NOT EXISTS customer_id BIGINT;
ALTER TABLE t_posting_order ADD COLUMN IF NOT EXISTS occupied_amount DECIMAL(14,2);
ALTER TABLE t_posting_order ADD COLUMN IF NOT EXISTS credit_used INT NOT NULL DEFAULT 0;
-- 一张报价单最多背一张授信上刊单（H2 唯一索引允许多个 NULL，普通单不受限）
CREATE UNIQUE INDEX IF NOT EXISTS uk_posting_order_quote ON t_posting_order (quote_no);
CREATE INDEX IF NOT EXISTS idx_posting_order_customer ON t_posting_order (customer_id);

-- 客户档案：客户名全局唯一（报价单 t_quote.customer_name 按它认领）；额度只认这一户的账，不记销售小本本
-- 信用额度状态：ACTIVE 在档 / FROZEN 冻结（冻结期间不占新额度，已占用不动）
CREATE TABLE IF NOT EXISTS t_customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_no VARCHAR(40) NOT NULL,
    customer_name VARCHAR(128) NOT NULL,
    owner_sales VARCHAR(64) NOT NULL,
    credit_limit DECIMAL(14,2) NOT NULL,
    occupied_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
    credit_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    current_version_id BIGINT,
    current_version_no INT,
    contact_name VARCHAR(64),
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_customer_no UNIQUE (customer_no),
    CONSTRAINT uk_customer_name UNIQUE (customer_name)
);
CREATE INDEX IF NOT EXISTS idx_customer_owner ON t_customer (owner_sales);
-- 信用额度版本（只追加留痕）：额度一动一个版本，前值后值都在；
-- 变更类型 INITIAL 建档 / ADJUST 调额 / FREEZE 冻结 / UNFREEZE 解冻；
-- 版本状态 PENDING 待审批 / EFFECTIVE 生效 / REJECTED 已驳回 / SUPERSEDED 已被新版本取代。
-- 建档即 v1 直接生效（前值 0）；之后调额/冻结一律先 PENDING，财务审批后才生效。
CREATE TABLE IF NOT EXISTS t_credit_limit_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    change_type VARCHAR(16) NOT NULL,
    before_limit DECIMAL(14,2),
    after_limit DECIMAL(14,2),
    before_status VARCHAR(16),
    after_status VARCHAR(16),
    status VARCHAR(16) NOT NULL,
    applicant_name VARCHAR(64) NOT NULL,
    apply_reason VARCHAR(255),
    apply_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approver_name VARCHAR(64),
    approve_comment VARCHAR(255),
    approve_time TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_credit_limit_version UNIQUE (customer_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_clv_customer ON t_credit_limit_version (customer_id);
CREATE INDEX IF NOT EXISTS idx_clv_status ON t_credit_limit_version (status);

