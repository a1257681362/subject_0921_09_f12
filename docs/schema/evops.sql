-- H2 本地文件数据库初始化脚本。
-- F1：户外广告点位与上刊底账（点位档案 / 按周档期 / 上刊单 / 对冲单 / 外部回执 / 逐单留底）

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- 单据号全局序列（单号唯一、单调，H2 序列保证并发取号不重）
CREATE SEQUENCE IF NOT EXISTS seq_order_no START WITH 1 INCREMENT BY 1;

-- 点位档案：编号、尺寸、朝向、商圈，一样不能少；site_no 重复存不进去
CREATE TABLE IF NOT EXISTS t_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_no VARCHAR(64) NOT NULL,
    size_spec VARCHAR(64) NOT NULL,
    orientation VARCHAR(32) NOT NULL,
    business_district VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'LISTED',
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_site_no UNIQUE (site_no)
);

-- 上刊单（含对冲单）：画面挂在点位上；状态 HUNG 挂起 / TAKEN_DOWN 落架 / OFFSET 已对冲
-- biz_period 按发生日 occur_date 落库时固化，跨月单不随查询日漂移
CREATE TABLE IF NOT EXISTS t_posting_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT,
    offset_of_order_id BIGINT,
    order_kind VARCHAR(16) NOT NULL DEFAULT 'POSTING',
    site_id BIGINT NOT NULL,
    creative_name VARCHAR(128) NOT NULL,
    week_start DATE NOT NULL,
    week_end DATE NOT NULL,
    occur_date DATE NOT NULL,
    biz_period CHAR(7) NOT NULL,
    status VARCHAR(16) NOT NULL,
    version_no INT NOT NULL DEFAULT 1,
    offset_reason VARCHAR(255),
    operator_name VARCHAR(64) NOT NULL,
    closed_time TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_posting_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_order_period ON t_posting_order (biz_period);
CREATE INDEX IF NOT EXISTS idx_order_site_week ON t_posting_order (site_id, week_start);
CREATE INDEX IF NOT EXISTS idx_order_root ON t_posting_order (root_order_id);

-- 按周档期占用：同一屏同一周只能挂一张画面；RELEASED 后该周可重新上刊
CREATE TABLE IF NOT EXISTS t_slot_booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    week_start DATE NOT NULL,
    week_end DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_slot_site_week UNIQUE (site_id, week_start)
);

-- 逐单事件留底（只追加，不改不删）：谁经手、哪天发生、当时单据快照全在这里，支撑版本选择与回退
CREATE TABLE IF NOT EXISTS t_order_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT NOT NULL,
    event_type VARCHAR(24) NOT NULL,
    version_no INT NOT NULL,
    occur_date DATE NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    related_order_no VARCHAR(40),
    detail VARCHAR(500),
    snapshot CLOB,
    event_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_event_order ON t_order_event (order_id, version_no);
CREATE INDEX IF NOT EXISTS idx_event_root ON t_order_event (root_order_id);

-- 外部回执：挂回原单据；即便回执指向对冲单，也回溯到根单
CREATE TABLE IF NOT EXISTS t_order_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT NOT NULL,
    root_order_no VARCHAR(40),
    source VARCHAR(64),
    content VARCHAR(1000),
    occur_date DATE,
    operator_name VARCHAR(64) NOT NULL,
    received_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_receipt_no UNIQUE (receipt_no)
);
CREATE INDEX IF NOT EXISTS idx_receipt_root ON t_order_receipt (root_order_id);
CREATE INDEX IF NOT EXISTS idx_receipt_order ON t_order_receipt (order_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-ledger-1', '户外广告点位与上刊底账：点位档案、按周档期、上刊/落架/对冲单、外部回执、逐单事件留底');

-- F2：素材流水与多规格转档（素材档案 / 转档版本 / 多规格产物 / 转档任务状态）

-- 素材编号、转档任务号全局序列
CREATE SEQUENCE IF NOT EXISTS seq_asset_no START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_transcode_job_no START WITH 1 INCREMENT BY 1;

-- 素材档案：一张原图一份档案；fingerprint_sha256 为文件指纹，同一张图重复上传认出来，不另开档
CREATE TABLE IF NOT EXISTS t_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_no VARCHAR(40) NOT NULL,
    fingerprint_sha256 CHAR(64) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(128),
    width INT NOT NULL,
    height INT NOT NULL,
    orientation VARCHAR(16) NOT NULL,
    file_size BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    upload_count INT NOT NULL DEFAULT 1,
    last_upload_time TIMESTAMP,
    latest_version_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_asset_no UNIQUE (asset_no),
    CONSTRAINT uk_asset_fingerprint UNIQUE (fingerprint_sha256)
);

-- 素材转档版本：每跑一轮转档（上传首轮 / 重新转档）记一版，转档状态挂在版本上
CREATE TABLE IF NOT EXISTS t_asset_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    source VARCHAR(16) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    width INT,
    height INT,
    storage_path VARCHAR(500) NOT NULL,
    transcode_status VARCHAR(16) NOT NULL,
    fail_reason VARCHAR(1000),
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_asset_version UNIQUE (asset_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_asset_version_asset ON t_asset_version (asset_id);

-- 多规格转档产物：一行一个规格版本，usage 标清用途（信息流横版 / 信息流竖版）
CREATE TABLE IF NOT EXISTS t_asset_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    usage VARCHAR(24) NOT NULL,
    width INT NOT NULL,
    height INT NOT NULL,
    long_edge INT NOT NULL,
    file_size BIGINT NOT NULL,
    quality_round INT NOT NULL,
    final_quality FLOAT,
    content_type VARCHAR(64) NOT NULL DEFAULT 'image/jpeg',
    storage_path VARCHAR(500) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_asset_version_usage UNIQUE (version_id, usage)
);
CREATE INDEX IF NOT EXISTS idx_asset_file_asset ON t_asset_file (asset_id);

-- 转档任务：多规格转档状态，PENDING/PROCESSING/SUCCESS/FAILED；失败原因落库让美工看得见，不干等
CREATE TABLE IF NOT EXISTS t_transcode_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_no VARCHAR(40) NOT NULL,
    asset_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    specs VARCHAR(255),
    success_count INT NOT NULL DEFAULT 0,
    fail_reason VARCHAR(1000),
    finished_time TIMESTAMP,
    operator_name VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_transcode_job_no UNIQUE (job_no)
);
CREATE INDEX IF NOT EXISTS idx_transcode_job_asset ON t_transcode_job (asset_id);
CREATE INDEX IF NOT EXISTS idx_transcode_job_version ON t_transcode_job (version_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f2-asset-transcode-1', '素材流水与多规格转档：素材档案按文件指纹去重，横竖两版常规规格自动转档、长边限像素、超标再压质量，转档状态与失败原因可见');

-- F3：点位经纬度建档与半径捞点（坐标建档版本 / 商圈圈界 / 半径检索 / 重叠带标记）

-- 点位档案补经纬度：十进制度 DECIMAL 落库，小数位不丢；geo_status 记经纬度建档状态
-- （ALTER ... IF NOT EXISTS：新库随上方 CREATE 后补齐，老库原地加列，两遍执行都安全）
ALTER TABLE t_site ADD COLUMN IF NOT EXISTS lat DECIMAL(10,7);
ALTER TABLE t_site ADD COLUMN IF NOT EXISTS lng DECIMAL(11,7);
ALTER TABLE t_site ADD COLUMN IF NOT EXISTS geo_status VARCHAR(16) NOT NULL DEFAULT 'UNFILED';
ALTER TABLE t_site ADD COLUMN IF NOT EXISTS geo_version_no INT;

-- 经纬度建档版本：每录一次坐标记一版（首建 INITIAL / 纠偏重录 CORRECT），旧版置 SUPERSEDED 不抹历史
CREATE TABLE IF NOT EXISTS t_site_geo_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    lat DECIMAL(10,7) NOT NULL,
    lng DECIMAL(11,7) NOT NULL,
    source VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_site_geo_version UNIQUE (site_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_site_geo_version_site ON t_site_geo_version (site_id);

-- 商圈圈界：拓展部圈的商圈落成中心坐标+半径（公里）；归属仍按点位录入时定的主商圈走
CREATE TABLE IF NOT EXISTS t_biz_district_circle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_name VARCHAR(128) NOT NULL,
    center_lat DECIMAL(10,7) NOT NULL,
    center_lng DECIMAL(11,7) NOT NULL,
    radius_km DECIMAL(8,3) NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_district_circle_name UNIQUE (district_name)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
