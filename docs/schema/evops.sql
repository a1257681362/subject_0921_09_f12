-- F4：年度刊例与统一计价（年度刊例 / 刊例版本 / 购买档期长度阶梯折扣 / 点位刊例价 / 报价单价快照）

-- 报价单号全局序列
CREATE SEQUENCE IF NOT EXISTS seq_quote_no START WITH 1 INCREMENT BY 1;

-- 年度刊例：一个自然年一份主档；状态 DRAFT 编制中 / EFFECTIVE 生效中 / CLOSED 已封存
-- 生效版本唯一；调价不许改生效版本，只能另起新版再发布
CREATE TABLE IF NOT EXISTS t_rate_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_no VARCHAR(40) NOT NULL,
    rate_year INT NOT NULL,
    card_name VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    current_version_id BIGINT,
    current_version_no INT,
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_rate_card_year UNIQUE (rate_year),
    CONSTRAINT uk_rate_card_no UNIQUE (card_no)
);

-- 年度刊例版本：草稿可配档位与点位价；发布后冻结，调价另起新版
-- 版本状态 DRAFT 草稿 / EFFECTIVE 生效中 / SUPERSEDED 已被新版取代 / REVOKED 已作废
CREATE TABLE IF NOT EXISTS t_rate_card_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    tax_rate DECIMAL(7,4) NOT NULL DEFAULT 0.0600,
    publish_time TIMESTAMP,
    revoke_time TIMESTAMP,
    revoke_reason VARCHAR(255),
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_rate_card_version UNIQUE (card_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_rcv_version_card ON t_rate_card_version (card_id);

-- 阶梯档位：按购买档期长度（周）落档，discount_rate 为档位比例（刊例价 × 比例 = 折后单价）
-- 档位区间 [min_weeks, max_weeks] 闭区间；max_weeks 为空表示“及以上”；同一版本档位不许重叠、不许断档
CREATE TABLE IF NOT EXISTS t_rate_card_tier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    tier_no INT NOT NULL,
    min_weeks INT NOT NULL,
    max_weeks INT,
    discount_rate DECIMAL(7,4) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_rate_card_tier UNIQUE (version_id, tier_no)
);
CREATE INDEX IF NOT EXISTS idx_rct_version ON t_rate_card_tier (version_id);

-- 点位刊例行：版本内每个点位一条挂牌周单价（未税）；发布后随版本冻结
CREATE TABLE IF NOT EXISTS t_rate_card_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    list_price DECIMAL(12,2) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_rate_card_site UNIQUE (version_id, site_id)
);
CREATE INDEX IF NOT EXISTS idx_rcs_version ON t_rate_card_site (version_id);
CREATE INDEX IF NOT EXISTS idx_rcs_site ON t_rate_card_site (site_id);

-- 报价单：按提交当天的生效刊例计价；刊例年份/版本/税率随单固化，后面调价不回写旧单
CREATE TABLE IF NOT EXISTS t_quote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_no VARCHAR(40) NOT NULL,
    customer_name VARCHAR(128) NOT NULL,
    submit_date DATE NOT NULL,
    rate_year INT NOT NULL,
    rate_card_id BIGINT NOT NULL,
    rate_card_no VARCHAR(40) NOT NULL,
    version_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    tax_rate DECIMAL(7,4) NOT NULL,
    total_ex_tax DECIMAL(14,2) NOT NULL,
    total_tax DECIMAL(14,2) NOT NULL,
    total_incl_tax DECIMAL(14,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'SUBMITTED',
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_quote_no UNIQUE (quote_no)
);
CREATE INDEX IF NOT EXISTS idx_quote_submit_date ON t_quote (submit_date);
CREATE INDEX IF NOT EXISTS idx_quote_version ON t_quote (version_id);

-- 报价行：单价快照——点位编号、挂牌单价、落档档位、档位比例、折后单价、含税/未税金额全部随行留底
CREATE TABLE IF NOT EXISTS t_quote_line (
